export function esIdiomaValido(valor: string): valor is Idioma {
  return (IDIOMAS_SOPORTADOS as readonly string[]).includes(valor);
}

export function normalizarIdioma(valor: string | null | undefined): Idioma | null {
  if (!valor) return null;

  const exacto = valor.trim();
  if (esIdiomaValido(exacto)) return exacto;

  const idioma = exacto.toLowerCase();
  if (idioma.startsWith('zh')) {
    if (
      idioma.includes('hant')
      || idioma.includes('-tw')
      || idioma.includes('_tw')
      || idioma.includes('-hk')
      || idioma.includes('_hk')
      || idioma.includes('-mo')
      || idioma.includes('_mo')
    ) {
      return 'zh-Hant';
    }
    return 'zh-Hans';
  }

  const base = idioma.split(/[-_]/)[0];
  return esIdiomaValido(base) ? base : null;
}

export function obtenerIdiomaNavegador(): Idioma {
  return normalizarIdioma(navigator.language) ?? 'en';
}

